import { useCallback, useEffect, useRef, useState, type KeyboardEvent, type ReactNode } from 'react';
import indexUrl from '../data/buxori-index.json?url';
import type { Engine, Status, Translation } from '../engine/engine.ts';
import type { BuxoriResult, Lookup, Tier, VerbAnalysis } from '../lib/lookup.ts';
import type { BuxoriIndex, Example, RootEntry } from '../lib/types.ts';
import type { Suggestion } from '../ai/similar.ts';
import { SimilarWords } from './Similar.tsx';

/**
 * Optional AI fallback (see translator/worker/), configured in index.html with
 * <div id="translator-root" data-ai-endpoint="https://…">. Absent = disabled: the
 * translator works entirely offline in the browser. When set, only non-verified
 * results are sent, with similar source examples for grounding; any API key stays
 * on the server.
 */
const AI_ENDPOINT = (typeof document !== 'undefined' && document.getElementById('translator-root')?.dataset['aiEndpoint']) || '';
const MAX = 2000;

type Loaded = {
  engine: Engine;
  lookup: Lookup;
  index: BuxoriIndex;
  toCyrillic: (s: string) => string;
  canonicalKey: (s: string) => string;
  inflectLike: (original: string, replacement: string, pos: string) => string;
};
type Picked = { from: string; to: string };
type Mode = 'en-bux' | 'bux-en';
type Script = 'latin' | 'cyrillic';

const BADGE: Record<Status | 'ai', { label: string; cls: string; help: string }> = {
  exact: { label: 'verified', cls: 'exact', help: 'Printed in the source material.' },
  grammar: { label: 'built from rules', cls: 'grammar', help: 'Assembled from source words with the grammar rules the source states. Check before relying on it.' },
  partial: { label: 'incomplete', cls: 'fuzzy', help: 'Built from rules, but some words are not in the source and are missing.' },
  fuzzy: { label: 'closest match', cls: 'fuzzy', help: 'Your spelling was corrected or matched to a close entry.' },
  compositional: { label: 'word by word', cls: 'compositional', help: 'Individual word glosses in English order. Not a sentence.' },
  none: { label: 'no match', cls: 'none', help: 'Not in the source and not buildable from it.' },
  ai: { label: 'ai-assisted', cls: 'ai', help: 'Generated by the AI fallback from similar source examples. Not verified.' },
};
const TIER_LABEL: Record<Tier, string> = {
  exact: 'exact spelling',
  fuzzy: 'ignoring accents and apostrophes',
  loose: 'approximate spelling (o/u, e/i)',
  skeleton: 'consonants only (a guess)',
};
const PERSON_EN: Record<string, string> = { '1sg': 'I', '2sg': 'you', '2pol': 'you, polite', '3sg': 'he/she', '3resp': 'he/she, respectful', '1pl': 'we', '2pl': 'you, plural', '3pl': 'they' };
const EVIDENCE_LABEL: Record<string, string> = {
  attested: 'printed in the source', stated: 'from a stated rule', derived: 'derived by rule', borrowed: 'borrowed (not in the source)',
};

async function load(): Promise<Loaded> {
  const [{ Engine }, { createLookup }, norm, { inflectLike }, res] = await Promise.all([
    import('../engine/engine.ts'), import('../lib/lookup.ts'), import('../lib/normalizer.ts'), import('../engine/english.ts'), fetch(indexUrl),
  ]);
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const index = (await res.json()) as BuxoriIndex;
  return { engine: new Engine(index), lookup: createLookup(index), index, toCyrillic: norm.toCyrillic, canonicalKey: (s) => norm.canonicalKey(norm.foldTsvStress(s)), inflectLike };
}

export function App() {
  const [loaded, setLoaded] = useState<Loaded | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [mode, setMode] = useState<Mode>('en-bux');
  const [script, setScript] = useState<Script>('latin');
  const [input, setInput] = useState('');
  const [result, setResult] = useState<{ kind: 'en'; r: Translation; unknown: string[]; picked?: Picked; ai?: { text: string; explanation?: string } } | { kind: 'bux'; r: BuxoriResult; verbs: (VerbAnalysis & { everyday?: string })[]; examples: Example[] } | null>(null);
  const [busy, setBusy] = useState(false);
  const [copied, setCopied] = useState(false);
  const inputRef = useRef<HTMLTextAreaElement>(null);

  useEffect(() => {
    let live = true;
    load().then((l) => { if (live) setLoaded(l); }).catch((e: unknown) => { if (live) setError(e instanceof Error ? e.message : String(e)); });
    return () => { live = false; };
  }, []);

  // Focus the input once the dataset is ready (the router focuses it before React mounts).
  useEffect(() => { if (loaded) inputRef.current?.focus({ preventScroll: true }); }, [loaded]);

  const show = useCallback((t: string) => (script === 'cyrillic' && loaded ? loaded.toCyrillic(t) : t), [script, loaded]);

  const run = useCallback(async (override?: string, picked?: Picked) => {
    if (!loaded || busy) return;
    const text = (override ?? input).trim();
    if (!text) { inputRef.current?.focus(); return; }
    setBusy(true);
    try {
      if (mode === 'en-bux') {
        const r = loaded.engine.translate(text);
        let ai: { text: string; explanation?: string } | undefined;
        if (AI_ENDPOINT && r.status !== 'exact') {
          try {
            const resp = await fetch(AI_ENDPOINT, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ text, examples: loaded.engine.related(text, 8) }) });
            if (resp.ok) { const d = (await resp.json()) as { translation?: string; explanation?: string }; if (d.translation) ai = { text: d.translation, ...(d.explanation ? { explanation: d.explanation } : {}) }; }
          } catch { /* offline result stands */ }
        }
        // English words the source lacks, for the "similar words" suggestions (only when nothing was translated).
        const unknown = r.status === 'none' && !ai ? loaded.engine.unknownWords(text) : [];
        setResult({ kind: 'en', r, unknown, ...(picked ? { picked } : {}), ...(ai ? { ai } : {}) });
      } else {
        const r = loaded.lookup.byBuxori(text);
        // Conjugated verb: analyse it, and show the everyday (Regular) form when the input is Literal (meravam → merum).
        const verbs = (r.matches.length ? [] : loaded.lookup.analyzeVerb(text)).map((v) => {
          const pn = v.ending?.personNumber;
          if (!pn || !v.tense) return v;
          const reg = loaded.engine.morph.conjugate(v.root, v.tense, pn, { negative: v.prefixes.includes('na') });
          return reg && reg.text !== loaded.canonicalKey(text) ? { ...v, everyday: reg.text } : v;
        });
        const key = loaded.canonicalKey(text);
        const examples = key.includes(' ') || !r.matches.length
          ? Object.values(loaded.index.examples).filter((e) => e.en && loaded.canonicalKey(e.bux).includes(key)).slice(0, 6)
          : [];
        setResult({ kind: 'bux', r, verbs, examples });
      }
    } finally { setBusy(false); }
  }, [loaded, busy, input, mode]);

  const onKey = (e: KeyboardEvent<HTMLTextAreaElement>) => {
    if ((e.ctrlKey || e.metaKey) && e.key === 'Enter') { e.preventDefault(); void run(); }
  };
  const switchMode = (m: Mode) => { setMode(m); setResult(null); inputRef.current?.focus(); };

  // A suggestion was picked: put it in the sentence (in the same form: purchased → bought) and translate that.
  const pick = (word: string, s: Suggestion) => {
    if (!loaded) return;
    const to = loaded.inflectLike(word, s.gloss, s.root.pos);
    const re = new RegExp(`(^|[^A-Za-z'’])${word.replace(/[-']/g, '[-\'’]?')}(?![A-Za-z])`, 'i');
    const m = re.exec(input);
    if (!m) return;   // the word came from normalised text ("u" → you) and isn't literally in the box
    const at = m.index + m[1]!.length;
    const next = input.slice(0, at) + matchCase(input.slice(at, m.index + m[0].length), to) + input.slice(m.index + m[0].length);
    setInput(next);
    void run(next, { from: word, to });
  };

  const copyText = result?.kind === 'en'
    ? (result.ai?.text ?? (result.r.variants.length ? result.r.variants.map((v) => `${v.register}: ${show(v.text)}`).join('\n') : result.r.text ? show(result.r.text) : ''))
    : '';
  const copy = () => {
    if (!copyText) return;
    void navigator.clipboard?.writeText(copyText).then(() => { setCopied(true); setTimeout(() => setCopied(false), 1200); });
  };

  const status = error ? `Dataset failed to load (${error})` : !loaded ? 'Loading dataset…' : busy ? 'Translating…'
    : `Ready · ${Object.keys(loaded.index.roots.entries).length.toLocaleString()} entries, ${Object.keys(loaded.index.examples).length.toLocaleString()} examples`;

  return (
    <div className="tr-wrap">
      <div className="tr-tabs" role="tablist" aria-label="Direction">
        <button type="button" role="tab" aria-selected={mode === 'en-bux'} className={mode === 'en-bux' ? 'active' : ''} onClick={() => switchMode('en-bux')}>English → Buxori</button>
        <button type="button" role="tab" aria-selected={mode === 'bux-en'} className={mode === 'bux-en' ? 'active' : ''} onClick={() => switchMode('bux-en')}>Buxori → English</button>
        <span className="tr-script" role="group" aria-label="Buxori script">
          <button type="button" aria-pressed={script === 'latin'} className={script === 'latin' ? 'active' : ''} onClick={() => setScript('latin')}>Latin</button>
          <button type="button" aria-pressed={script === 'cyrillic'} className={script === 'cyrillic' ? 'active' : ''} onClick={() => setScript('cyrillic')}>Кирилл</button>
        </span>
      </div>

      <div className="tr-panes">
        <div className="tr-pane">
          <div className="tr-pane-head">
            <span>{mode === 'en-bux' ? 'English' : 'Buxori'}</span>
            <span className="tr-sub">{mode === 'en-bux' ? 'source' : 'Latin, Cyrillic or Hebrew script'}</span>
          </div>
          <textarea id="trInput" ref={inputRef} className="tr-input" rows={6} maxLength={MAX} value={input}
            aria-label={mode === 'en-bux' ? 'English text' : 'Buxori word or phrase'}
            placeholder={mode === 'en-bux' ? 'Type English text to translate into Buxori…' : 'Type a Buxori word (e.g. kitov, Худо, meravam)…'}
            spellCheck={false} autoComplete="off" onChange={(e) => setInput(e.target.value)} onKeyDown={onKey} />
          <div className="tr-pane-foot">
            <button type="button" className="tr-iconbtn" onClick={() => { setInput(''); setResult(null); inputRef.current?.focus(); }}>Clear</button>
            <span className="tr-count">{input.length}/{MAX}</span>
          </div>
        </div>

        <div className="tr-pane">
          <div className="tr-pane-head">
            <span>{mode === 'en-bux' ? 'Buxori' : 'English'}</span>
            <span className="tr-sub">{mode === 'en-bux' ? (script === 'cyrillic' ? 'Cyrillic transliteration' : 'Bukharian · Judeo-Tajik') : 'dictionary'}</span>
          </div>
          <div className={`tr-output${result ? '' : ' tr-empty'}`} aria-live="polite" id="trOutput">
            {!result ? 'Translation will appear here.' : result.kind === 'en' ? <EnOutput res={result.r} ai={result.ai} show={show} /> : <BuxOutput res={result.r} verbs={result.verbs} show={show} />}
          </div>
          <div className="tr-pane-foot">
            <button type="button" className="tr-iconbtn" disabled={!copyText} onClick={copy}>{copied ? 'Copied' : 'Copy'}</button>
            <span className="tr-count">{result?.kind === 'en' && result.r.status !== 'none' ? <Badge status={result.ai ? 'ai' : result.r.status} conf={result.r.confidence} /> : null}</span>
          </div>
        </div>
      </div>

      <div className="tr-controls">
        <button id="trGo" type="button" className="btn btn-primary" disabled={!loaded || busy} onClick={() => void run()}>
          {busy ? <><span className="tr-spinner" />Translating</> : 'Translate'}
        </button>
        <span id="trStatus" className="tr-status">{status}</span>
      </div>

      {result?.kind === 'en' && <EnDetails res={result.r} ai={result.ai} picked={result.picked} show={show} />}
      {result?.kind === 'en' && loaded && <SimilarWords words={result.unknown} engine={loaded.engine} show={show} onPick={pick} />}
      {result?.kind === 'bux' && <BuxDetails res={result.r} verbs={result.verbs} examples={result.examples} show={show} />}

      <p className="tr-disclaimer">
        Grounded in a curated Bukharian (Judeo-Tajik) lesson book. “Verified” results are printed in the source; “built from rules”
        results combine source words using the grammar the source states, and every step is shown. Missing words are reported,
        never invented. Everyday (Regular) register is used by default. Cyrillic is a transliteration of the source’s Latin spelling.
      </p>
    </div>
  );
}

function Badge({ status, conf }: { status: Status | 'ai'; conf: number }) {
  const b = BADGE[status];
  return <><span className={`tr-badge ${b.cls}`} title={b.help}>{b.label}</span>{conf ? <span className="tr-conf">conf {conf.toFixed(2)}</span> : null}</>;
}

function EnOutput({ res, ai, show }: { res: Translation; ai: { text: string } | undefined; show: (s: string) => string }) {
  if (ai) return <>{show(ai.text)}</>;
  if (!res.text) return <span className="tr-empty">— no reliable translation —</span>;
  if (res.variants.length) {
    return <>{res.variants.map((v) => (
      <div className="tr-variant" key={v.register}><span className="tr-reg">{v.register}</span><span className="tr-vbux">{show(v.text)}</span></div>
    ))}</>;
  }
  return <>{show(res.text)}</>;
}

function Note({ kind, children }: { kind?: 'warn' | 'miss'; children: ReactNode }) {
  return <div className={`tr-note${kind ? ' ' + kind : ''}`}>{children}</div>;
}

function Rows({ rows }: { rows: number[] | undefined }) {
  if (!rows?.length) return null;
  return <span className="tr-rows" title="Line numbers in translator/data/bukhori.tsv">TSV {rows.slice(0, 4).join(', ')}{rows.length > 4 ? '…' : ''}</span>;
}

function EnDetails({ res, ai, picked, show }: { res: Translation; ai: { text: string; explanation?: string } | undefined; picked: Picked | undefined; show: (s: string) => string }) {
  const b = BADGE[res.status];
  return (
    <>
      <div id="trNote">
        {picked && <Note kind="warn"><span className="tr-badge ai">your pick</span>“{picked.to}” is used for “{picked.from}”, from the AI suggestions. This is a translation of the edited sentence, so check that it still means what you meant.</Note>}
        {ai && <Note kind="warn"><span className="tr-badge ai">ai-assisted</span>Generated by the AI fallback from similar source examples. Not verified.{ai.explanation ? ` ${ai.explanation}` : ''}</Note>}
        {res.status === 'none' && <Note kind="miss"><span className="tr-badge none">no match</span>{res.notes[0]}</Note>}
        {res.hint && (
          <Note>
            <span className="tr-badge compositional">{res.hint.kind === 'partial' ? 'incomplete draft' : 'word glosses'}</span>
            Not a translation. {res.hint.kind === 'partial' ? 'The words that were found, in Buxori order:' : 'The individual words that were found, in English order:'}{' '}
            {res.hint.variants.length ? res.hint.variants.map((v) => <span key={v.register} className="tr-alt"><code>{show(v.text)}</code> <em>{v.register}</em></span>) : <code>{show(res.hint.text)}</code>}
          </Note>
        )}
        {res.status !== 'none' && res.status !== 'exact' && <Note kind="warn"><span className={`tr-badge ${b.cls}`}>{b.label}</span>{b.help}{res.evidence ? ` Least certain part: ${EVIDENCE_LABEL[res.evidence]}.` : ''}</Note>}
        {res.review && <Note kind="warn"><span className="tr-badge fuzzy">review</span>The source marks this entry as uncertain.</Note>}
        {res.unknown.length > 0 && <Note kind="warn">Not in the source (left out): {res.unknown.map((w) => <code key={w}>{w}</code>)}</Note>}
        {res.notes.filter((n) => res.status !== 'none' || n !== res.notes[0]).map((n) => <Note key={n}>{n}</Note>)}
        {res.alternatives.length > 0 && (
          <Note>Other forms: {res.alternatives.slice(0, 8).map((a, i) => (
            <span key={i} className="tr-alt"><code>{show(a.text)}</code>{a.note ? <em> {a.note}</em> : null}</span>
          ))}</Note>
        )}
      </div>
      {(res.steps.length > 0 || res.related.length > 0) && (
        <div className="tr-explain">
          {res.steps.length > 0 && (
            <details open={res.status !== 'exact'}>
              <summary className="tr-explain-head">// How this was built</summary>
              <ol className="tr-steps">{res.steps.map((s, i) => <li key={i}>{s.text} <Rows rows={s.rows} /></li>)}</ol>
            </details>
          )}
          {res.related.length > 0 && (
            <div className="tr-related">
              <div className="tr-explain-head">// Similar sentences in the source</div>
              <ul>{res.related.map((x) => <li key={x.row}>{x.en} → <code>{show(x.bux)}</code> <Rows rows={[x.row]} /></li>)}</ul>
            </div>
          )}
        </div>
      )}
    </>
  );
}

function BuxOutput({ res, verbs, show }: { res: BuxoriResult; verbs: VerbAnalysis[]; show: (s: string) => string }) {
  if (!res.matches.length && verbs[0]) {
    const v = verbs[0];
    const who = v.ending?.personNumber ? PERSON_EN[v.ending.personNumber] : '';
    return <>{v.root.glosses[0]?.text ?? ''}{who ? ` (${who}${v.tense ? ', ' + v.tense.replace(/_/g, ' ') : ''})` : ''}<div className="tr-sub-out">form of {show(v.root.lemma.text)}</div></>;
  }
  if (!res.matches.length) return <span className="tr-empty">— not found —</span>;
  const first = res.matches[0]!;
  const gl = [...first.roots.flatMap((e) => e.glosses.map((g) => g.text)), ...first.inflected.flatMap((e) => e.glosses.map((g) => g.text))];
  return <>{[...new Set(gl)].slice(0, 4).join('; ')}<div className="tr-sub-out">{show(first.roots[0]?.lemma.text ?? first.inflected[0]?.text ?? first.key)}</div></>;
}

function Entry({ e, show }: { e: RootEntry; show: (s: string) => string }) {
  const v = e.verb;
  return (
    <li className="tr-entry">
      <strong>{show(e.lemma.text)}</strong> <span className="tr-pos">{e.pos.replace('_', ' ')}</span> — {e.glosses.map((g) => g.text).join('; ')}
      {v && <div className="tr-entry-sub">present stem <code>-{v.presentStem?.text ?? '?'}-</code>{v.presentStem && v.presentStem.evidence !== 'stated' ? ` (${EVIDENCE_LABEL[v.presentStem.evidence]})` : ''}, past stem <code>-{v.pastStem.text}-</code>{v.irregular ? ', irregular' : ''}{v.compound ? `, compound verb with “${v.compound.preverb}”` : ''}</div>}
      {e.forms.length > 0 && <div className="tr-entry-sub">also: {e.forms.slice(0, 5).map((f, i) => <span key={i}><code>{show(f.text)}</code> <em>{f.kind.replace('_', ' ')}</em> </span>)}</div>}
      <Rows rows={e.sources.map((s) => s.row)} />
    </li>
  );
}

function BuxDetails({ res, verbs, examples, show }: { res: BuxoriResult; verbs: (VerbAnalysis & { everyday?: string })[]; examples: Example[]; show: (s: string) => string }) {
  return (
    <>
      <div id="trNote">
        {res.tier && res.tier !== 'exact' && <Note kind="warn"><span className="tr-badge fuzzy">{TIER_LABEL[res.tier]}</span>Your input was read as <code>{res.canonical}</code>; these are the nearest entries.</Note>}
        {res.script !== 'latin' && res.script !== 'none' && <Note>Read from {res.script} script as <code>{res.canonical}</code>.</Note>}
        {!res.matches.length && !verbs.length && !examples.length && <Note kind="miss"><span className="tr-badge none">no match</span>Not found in the source, in any spelling.</Note>}
      </div>
      <div className="tr-explain">
        {res.matches.length > 0 && <ul className="tr-entries">{res.matches.flatMap((m) => [
          ...m.roots.map((e) => <Entry key={e.id} e={e} show={show} />),
          ...m.inflected.map((e, i) => <li key={`${m.key}-${i}`} className="tr-entry"><strong>{show(e.text)}</strong> — {e.glosses.map((g) => g.text).join('; ')}<div className="tr-entry-sub">inflected form{e.baseText ? ` of ${show(e.baseText)}` : ''}</div><Rows rows={[e.source.row]} /></li>),
        ])}</ul>}
        {verbs.length > 0 && (
          <div><div className="tr-explain-head">// Verb form</div>
            <ul className="tr-entries">{verbs.map((v, i) => (
              <li key={i} className="tr-entry"><strong>{show(v.root.lemma.text)}</strong> — {v.root.glosses[0]?.text}
                <div className="tr-entry-sub">{v.prefixes.length ? `${v.prefixes.join('- + ')}- + ` : ''}{v.stem.replace('_', ' ')} stem <code>{v.stemText}</code>{v.ending ? ` + ${v.ending.allomorphs[0]?.form} (${v.tense?.replace(/_/g, ' ') ?? ''}, ${v.ending.personNumber ? PERSON_EN[v.ending.personNumber] : ''})` : ''}</div>
                {v.everyday && <div className="tr-entry-sub">Everyday (Regular) form: <code>{show(v.everyday)}</code></div>}</li>
            ))}</ul></div>
        )}
        {examples.length > 0 && (
          <div className="tr-related"><div className="tr-explain-head">// In source sentences</div>
            <ul>{examples.map((x) => <li key={x.id}><code>{show(x.bux)}</code> — {x.en} <Rows rows={[x.source.row]} /></li>)}</ul></div>
        )}
      </div>
    </>
  );
}

/** "Purchase" → "Buy": keep the capital of the word being replaced. */
function matchCase(original: string, replacement: string): string {
  return /^[A-Z]/.test(original) ? replacement.charAt(0).toUpperCase() + replacement.slice(1) : replacement;
}
